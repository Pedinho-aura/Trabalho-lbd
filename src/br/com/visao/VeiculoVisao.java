    private void jBExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBExcluirActionPerformed
        // TODO add your handling code here:  
        String placa = jTPlaca.getText().trim();

        if (placa.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Selecione um veículo na tabela para excluí-lo.",
                    "Nenhum veículo selecionado",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirmacao = JOptionPane.showConfirmDialog(this,
                "Deseja realmente excluir o veículo de placa "
                        + placa + "?",
                "Confirmar exclusão",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE);

        if (confirmacao != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            VeiculoControle controle = new VeiculoControle();

            boolean excluido = controle.excluir(placa);

            if (excluido) {
                carregarVeiculos();

                jTPlaca.setText("");
                jTModelo.setText("");
                jTCliente.setText("");

                JOptionPane.showMessageDialog(this,
                        "Veículo excluído com sucesso!",
                        "Exclusão",
                        JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this,
                        "Não foi possível excluir o veículo. "
                                + "Verifique se ele ainda existe.",
                        "Aviso",
                        JOptionPane.WARNING_MESSAGE);
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Erro ao excluir veículo: " + e.getMessage(),
                    "Erro no banco de dados",
                    JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jBExcluirActionPerformed

