    private void jBCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBCadastrarActionPerformed
        // TODO add your handling code here:

        String placa = jTPlaca.getText().trim();
        String modelo = jTModelo.getText().trim();
        String idClienteTexto = jTCliente.getText().trim();

        if (placa.isEmpty() || modelo.isEmpty() || idClienteTexto.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Preencha a placa, o modelo e o ID do cliente.",
                "Campos obrigatórios",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        try {
            int idCliente = Integer.parseInt(idClienteTexto);

            VeiculoControle controle = new VeiculoControle();

            boolean cadastrado = controle.cadastrar(
                placa,
                modelo,
                idCliente
            );

            if (cadastrado) {
                carregarVeiculos();

                jTPlaca.setText("");
                jTModelo.setText("");
                jTCliente.setText("");

                JOptionPane.showMessageDialog(
                    this,
                    "Veículo cadastrado com sucesso!",
                    "Cadastro",
                    JOptionPane.INFORMATION_MESSAGE
                );
            } else {
                JOptionPane.showMessageDialog(
                    this,
                    "Não foi possível cadastrar o veículo.",
                    "Aviso",
                    JOptionPane.WARNING_MESSAGE
                );
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(
                this,
                "O ID do cliente deve ser um número inteiro válido.",
                "ID inválido",
                JOptionPane.WARNING_MESSAGE
            );

        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Dados inválidos",
                JOptionPane.WARNING_MESSAGE
            );

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                this,
                "Erro ao cadastrar veículo: " + e.getMessage(),
                "Erro no banco de dados",
                JOptionPane.ERROR_MESSAGE
            );
        }

       
    }//GEN-LAST:event_jBCadastrarActionPerformed

    private void jBAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBAtualizarActionPerformed
        // TODO add your handling code here:
        String placa = jTPlaca.getText().trim();
        String modelo = jTModelo.getText().trim();
        String idClienteTexto = jTCliente.getText().trim();

        if (placa.isEmpty() || modelo.isEmpty() || idClienteTexto.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Selecione um veículo e preencha todos os campos.",
                    "Campos obrigatórios",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirmacao = JOptionPane.showConfirmDialog(this,
                "Deseja realmente atualizar os dados deste veículo?",
                "Confirmar atualização",
                JOptionPane.YES_NO_OPTION);

        if (confirmacao != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            int idCliente = Integer.parseInt(idClienteTexto);

            VeiculoControle controle = new VeiculoControle();

            boolean atualizado = controle.atualizar(
                    placa, modelo, idCliente);

            if (atualizado) {
                carregarVeiculos();

                JOptionPane.showMessageDialog(this,
                        "Veículo atualizado com sucesso!",
                        "Atualização",
                        JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this,
                        "Nenhum veículo foi atualizado. Verifique a placa informada.",
                        "Aviso",
                        JOptionPane.WARNING_MESSAGE);
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "O ID do cliente deve ser um número inteiro válido.",
                    "ID inválido",
                    JOptionPane.WARNING_MESSAGE);

        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this,
                    e.getMessage(),
                    "Dados inválidos",
                    JOptionPane.WARNING_MESSAGE);

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Erro ao atualizar veículo: " + e.getMessage(),
                    "Erro no banco de dados",
                    JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jBAtualizarActionPerformed

