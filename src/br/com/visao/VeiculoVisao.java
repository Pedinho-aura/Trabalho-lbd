private void carregarVeiculos() throws SQLException {
    VeiculoControle controle = new VeiculoControle();
    List<Veiculo> veiculos = controle.listarTodos();

    DefaultTableModel modelo = new DefaultTableModel(
        new Object[]{"Placa", "Modelo", "ID do Cliente"}, 0
    ) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };

    for (Veiculo veiculo : veiculos) {
        modelo.addRow(new Object[]{
            veiculo.getPlaca(),
            veiculo.getModelo(),
            veiculo.getIdCliente()
        });
    }

    jTResultado.setModel(modelo);
}

