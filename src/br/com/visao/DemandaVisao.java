private void carregarDemandas() {
    try {
        DemandaControle controle = new DemandaControle();
        List<Demanda> demandas = controle.listarTodos();

        DefaultTableModel modelo = new DefaultTableModel(
                new Object[]{
                    "ID", "Status", "Data e hora de abertura", "Placa"
                }, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        for (Demanda demanda : demandas) {
            modelo.addRow(new Object[]{
                demanda.getIdDemanda(),
                demanda.getStatus(),
                demanda.getDataHoraAbertura(),
                demanda.getPlaca()
            });
        }

        jTResultado.setModel(modelo);

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Erro ao carregar demandas: " + e.getMessage(),
                "Erro no banco de dados",
                JOptionPane.ERROR_MESSAGE);
    }
}

