    private void jBExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBExcluirActionPerformed
        // TODO add your handling code here:   
        String idTexto = jTDemanda.getText().trim();

        if (idTexto.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Selecione uma demanda na tabela antes de excluir.",
                    "Nenhuma demanda selecionada",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int idDemanda = Integer.parseInt(idTexto);

            int confirmacao = JOptionPane.showConfirmDialog(this,
                    "Deseja realmente excluir a demanda de ID "
                            + idDemanda + "?",
                    "Confirmar exclusão",
                    JOptionPane.YES_NO_OPTION,
                    JOptionPane.WARNING_MESSAGE);

            if (confirmacao != JOptionPane.YES_OPTION) {
                return;
            }

            DemandaControle controle = new DemandaControle();

            boolean excluida = controle.excluir(idDemanda);

            if (excluida) {
                carregarDemandas();

                jTDemanda.setText("");
                jTStatus.setText("");
                jTDataHoraAbertura.setText("");
                jTPlaca.setText("");

                JOptionPane.showMessageDialog(this,
                        "Demanda excluída com sucesso!",
                        "Exclusão",
                        JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this,
                        "Nenhuma demanda foi excluída. Verifique o ID.",
                        "Aviso",
                        JOptionPane.WARNING_MESSAGE);
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "O ID da demanda deve ser um número inteiro.",
                    "ID inválido",
                    JOptionPane.WARNING_MESSAGE);

        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this,
                    e.getMessage(),
                    "Dados inválidos",
                    JOptionPane.WARNING_MESSAGE);

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Erro ao excluir demanda: " + e.getMessage()
                            + "\nVerifique se existem registros vinculados a ela.",
                    "Erro no banco de dados",
                    JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jBExcluirActionPerformed

