    private void jBCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBCadastrarActionPerformed
        // TODO add your handling code here:
        String status = jTStatus.getText().trim();
        String dataTexto = jTDataHoraAbertura.getText().trim();
        String placa = jTPlaca.getText().trim();

        if (status.isEmpty() || dataTexto.isEmpty() || placa.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Preencha o status, a data/hora de abertura e a placa.",
                    "Campos obrigatórios",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            java.time.LocalDateTime dataHoraAbertura =
                    java.time.LocalDateTime.parse(dataTexto);

            DemandaControle controle = new DemandaControle();

            int idGerado = controle.cadastrar(
                    status, dataHoraAbertura, placa);

            carregarDemandas();

            jTDemanda.setText(String.valueOf(idGerado));
            jTStatus.setText("");
            jTDataHoraAbertura.setText("");
            jTPlaca.setText("");

            JOptionPane.showMessageDialog(this,
                    "Demanda cadastrada com sucesso!\nID: " + idGerado,
                    "Cadastro",
                    JOptionPane.INFORMATION_MESSAGE);

        } catch (java.time.format.DateTimeParseException e) {
            JOptionPane.showMessageDialog(this,
                    "Informe a data e hora no formato AAAA-MM-DDTHH:MM:SS.\n"
                            + "Exemplo: 2026-10-18T14:30:00",
                    "Data/hora inválida",
                    JOptionPane.WARNING_MESSAGE);

        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this,
                    e.getMessage(),
                    "Dados inválidos",
                    JOptionPane.WARNING_MESSAGE);

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Erro ao cadastrar demanda: " + e.getMessage(),
                    "Erro no banco de dados",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBCadastrarActionPerformed

    private void jBAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBAtualizarActionPerformed
        // TODO add your handling code here:      
        String idTexto = jTDemanda.getText().trim();
        String status = jTStatus.getText().trim();
        String dataTexto = jTDataHoraAbertura.getText().trim();
        String placa = jTPlaca.getText().trim();

        if (idTexto.isEmpty() || status.isEmpty()
                || dataTexto.isEmpty() || placa.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Selecione uma demanda e preencha todos os campos.",
                    "Campos obrigatórios",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int idDemanda = Integer.parseInt(idTexto);

            java.time.LocalDateTime dataHoraAbertura =
                    java.time.LocalDateTime.parse(dataTexto);

            int confirmacao = JOptionPane.showConfirmDialog(this,
                    "Deseja realmente atualizar esta demanda?",
                    "Confirmar atualização",
                    JOptionPane.YES_NO_OPTION);

            if (confirmacao != JOptionPane.YES_OPTION) {
                return;
            }

            DemandaControle controle = new DemandaControle();

            boolean atualizado = controle.atualizar(
                    idDemanda,
                    status,
                    dataHoraAbertura,
                    placa
            );

            if (atualizado) {
                carregarDemandas();

                JOptionPane.showMessageDialog(this,
                        "Demanda atualizada com sucesso!",
                        "Atualização",
                        JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this,
                        "Nenhuma demanda foi atualizada. Verifique o ID.",
                        "Aviso",
                        JOptionPane.WARNING_MESSAGE);
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "O ID da demanda deve ser um número inteiro.",
                    "ID inválido",
                    JOptionPane.WARNING_MESSAGE);

        } catch (java.time.format.DateTimeParseException e) {
            JOptionPane.showMessageDialog(this,
                    "Informe a data e hora no formato AAAA-MM-DDTHH:MM:SS.",
                    "Data/hora inválida",
                    JOptionPane.WARNING_MESSAGE);

        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this,
                    e.getMessage(),
                    "Dados inválidos",
                    JOptionPane.WARNING_MESSAGE);

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Erro ao atualizar demanda: " + e.getMessage(),
                    "Erro no banco de dados",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBAtualizarActionPerformed

