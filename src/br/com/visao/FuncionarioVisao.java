private void carregarFuncionarios() {
    try {
        FuncionarioControle controle = new FuncionarioControle();
        List<Funcionario> funcionarios = controle.listarTodos();

        DefaultTableModel modelo = new DefaultTableModel(
                new Object[]{
                    "ID", "Nome", "CPF",
                    "Data de admissão", "ID do supervisor"
                }, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        for (Funcionario funcionario : funcionarios) {
            modelo.addRow(new Object[]{
                funcionario.getIdFuncionario(),
                funcionario.getNome(),
                funcionario.getCpf(),
                funcionario.getDataAdmissao(),
                funcionario.getIdSupervisor()
            });
        }

        jTResultado.setModel(modelo);

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Erro ao carregar funcionários: " + e.getMessage(),
                "Erro no banco de dados",
                JOptionPane.ERROR_MESSAGE);
    }
}

