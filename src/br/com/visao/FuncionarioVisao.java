    private void jTResultadoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTResultadoMouseClicked
        // TODO add your handling code here:
        int linha = jTResultado.getSelectedRow();

        if (linha >= 0) {
            jTFuncionario.setText(
                    jTResultado.getValueAt(linha, 0).toString());

            jTNome.setText(
                    jTResultado.getValueAt(linha, 1).toString());

            jTCPF.setText(
                    jTResultado.getValueAt(linha, 2).toString());

            jTDataAdmissao.setText(
                    jTResultado.getValueAt(linha, 3).toString());

            Object supervisor = jTResultado.getValueAt(linha, 4);

            if (supervisor == null
                    || supervisor.toString().equals("null")) {
                jTIDSupervisor.setText("");
            } else {
                jTIDSupervisor.setText(supervisor.toString());
            }
        }
    }//GEN-LAST:event_jTResultadoMouseClicked

    private void jBCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBCadastrarActionPerformed
        // TODO add your handling code here:
        
String nome = jTNome.getText().trim();
String cpf = jTCPF.getText().trim();
String dataTexto = jTDataAdmissao.getText().trim();
String supervisorTexto = jTIDSupervisor.getText().trim();

if (nome.isEmpty() || cpf.isEmpty() || dataTexto.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Preencha o nome, o CPF e a data de admissão.",
            "Campos obrigatórios",
            JOptionPane.WARNING_MESSAGE);
    return;
}

try {
    LocalDate dataAdmissao = LocalDate.parse(dataTexto);

    Integer idSupervisor = null;

    if (!supervisorTexto.isEmpty()) {
        idSupervisor = Integer.parseInt(supervisorTexto);
    }

    FuncionarioControle controle = new FuncionarioControle();

    int idGerado = controle.cadastrar(
            nome, cpf, dataAdmissao, idSupervisor);

    carregarFuncionarios();

    jTFuncionario.setText(String.valueOf(idGerado));
    jTNome.setText("");
    jTCPF.setText("");
    jTDataAdmissao.setText("");
    jTIDSupervisor.setText("");

    JOptionPane.showMessageDialog(this,
            "Funcionário cadastrado com sucesso!\nID: " + idGerado,
            "Cadastro",
            JOptionPane.INFORMATION_MESSAGE);

} catch (java.time.format.DateTimeParseException e) {
    JOptionPane.showMessageDialog(this,
            "Digite a data no formato AAAA-MM-DD. Exemplo: 2026-10-18.",
            "Data inválida",
            JOptionPane.WARNING_MESSAGE);

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "O ID do supervisor deve ser um número inteiro válido.",
            "ID inválido",
            JOptionPane.WARNING_MESSAGE);

} catch (IllegalArgumentException e) {
    JOptionPane.showMessageDialog(this,
            e.getMessage(),
            "Dados inválidos",
            JOptionPane.WARNING_MESSAGE);

} catch (SQLException e) {
    JOptionPane.showMessageDialog(this,
            "Erro ao cadastrar funcionário: " + e.getMessage(),
            "Erro no banco de dados",
            JOptionPane.ERROR_MESSAGE);
}

    }//GEN-LAST:event_jBCadastrarActionPerformed

    private void jBAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBAtualizarActionPerformed
        // TODO add your handling code here:  
        String idTexto = jTFuncionario.getText().trim();
        String nome = jTNome.getText().trim();
        String cpf = jTCPF.getText().trim();
        String dataTexto = jTDataAdmissao.getText().trim();
        String supervisorTexto = jTIDSupervisor.getText().trim();

        if (idTexto.isEmpty() || nome.isEmpty()
                || cpf.isEmpty() || dataTexto.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Preencha o ID, nome, CPF e data de admissão.",
                    "Campos obrigatórios",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirmacao = JOptionPane.showConfirmDialog(this,
                "Deseja realmente atualizar os dados deste funcionário?",
                "Confirmar atualização",
                JOptionPane.YES_NO_OPTION);

        if (confirmacao != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            int idFuncionario = Integer.parseInt(idTexto);
            LocalDate dataAdmissao = LocalDate.parse(dataTexto);

            Integer idSupervisor = null;

            if (!supervisorTexto.isEmpty()) {
                idSupervisor = Integer.parseInt(supervisorTexto);
            }

            FuncionarioControle controle = new FuncionarioControle();

            boolean atualizado = controle.atualizar(
                    idFuncionario,
                    nome,
                    cpf,
                    dataAdmissao,
                    idSupervisor
            );

            if (atualizado) {
                carregarFuncionarios();

                JOptionPane.showMessageDialog(this,
                        "Funcionário atualizado com sucesso!",
                        "Atualização",
                        JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this,
                        "Não foi possível atualizar o funcionário. "
                                + "Verifique se o ID informado existe.",
                        "Aviso",
                        JOptionPane.WARNING_MESSAGE);
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "O ID do funcionário e o ID do supervisor "
                            + "devem ser números inteiros válidos.",
                    "ID inválido",
                    JOptionPane.WARNING_MESSAGE);

        } catch (java.time.format.DateTimeParseException e) {
            JOptionPane.showMessageDialog(this,
                    "Digite a data no formato AAAA-MM-DD. Exemplo: 2026-01-15.",
                    "Data inválida",
                    JOptionPane.WARNING_MESSAGE);

        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this,
                    e.getMessage(),
                    "Dados inválidos",
                    JOptionPane.WARNING_MESSAGE);

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Erro ao atualizar funcionário: " + e.getMessage(),
                    "Erro no banco de dados",
                    JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jBAtualizarActionPerformed

