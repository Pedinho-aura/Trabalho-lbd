    private void jBExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBExcluirActionPerformed
        // TODO add your handling code here: 
        String idTexto = jTFuncionario.getText().trim();

        if (idTexto.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Selecione um funcionário na tabela para excluí-lo.",
                    "Nenhum funcionário selecionado",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirmacao = JOptionPane.showConfirmDialog(this,
                "Deseja realmente excluir o funcionário de ID "
                        + idTexto + "?",
                "Confirmar exclusão",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE);

        if (confirmacao != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            int idFuncionario = Integer.parseInt(idTexto);

            FuncionarioControle controle = new FuncionarioControle();
            boolean excluido = controle.excluir(idFuncionario);

            if (excluido) {
                carregarFuncionarios();

                jTFuncionario.setText("");
                jTNome.setText("");
                jTCPF.setText("");
                jTDataAdmissao.setText("");
                jTIDSupervisor.setText("");

                JOptionPane.showMessageDialog(this,
                        "Funcionário excluído com sucesso!",
                        "Exclusão",
                        JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this,
                        "Não foi possível excluir o funcionário. "
                                + "Verifique se ele ainda existe.",
                        "Aviso",
                        JOptionPane.WARNING_MESSAGE);
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "O ID do funcionário deve ser um número inteiro válido.",
                    "ID inválido",
                    JOptionPane.WARNING_MESSAGE);

        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this,
                    e.getMessage(),
                    "Dados inválidos",
                    JOptionPane.WARNING_MESSAGE);

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Erro ao excluir funcionário: " + e.getMessage(),
                    "Erro no banco de dados",
                    JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jBExcluirActionPerformed

