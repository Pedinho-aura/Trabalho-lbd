    private void jBCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBCadastrarActionPerformed
        // TODO add your handling code here:
        String valorTexto = jTValor.getText().trim().replace(",", ".");
        String dataTexto = jTDataHora.getText().trim();
        String demandaTexto = jTIDDemanda.getText().trim();
        String formaTexto = jTIDFormaPagamento.getText().trim();

        if (valorTexto.isEmpty() || dataTexto.isEmpty()
                || demandaTexto.isEmpty() || formaTexto.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Preencha todos os campos do pagamento.",
                "Campos obrigatórios",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        try {
            BigDecimal valor = new BigDecimal(valorTexto);
            LocalDateTime dataHora = LocalDateTime.parse(dataTexto);
            int idDemanda = Integer.parseInt(demandaTexto);
            int idForma = Integer.parseInt(formaTexto);

            PagamentoControle controle = new PagamentoControle();

            int idGerado = controle.cadastrar(
                valor, dataHora, idDemanda, idForma
            );

            carregarPagamentos();
            limparCampos();

            JOptionPane.showMessageDialog(
                this,
                "Pagamento cadastrado com sucesso! ID: " + idGerado,
                "Cadastro",
                JOptionPane.INFORMATION_MESSAGE
            );

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(
                this,
                "Informe um valor numérico válido e IDs inteiros.",
                "Dados inválidos",
                JOptionPane.WARNING_MESSAGE
            );
        } catch (java.time.format.DateTimeParseException e) {
            JOptionPane.showMessageDialog(
                this,
                "Data inválida. Utilize o formato yyyy-MM-ddTHH:mm:ss.",
                "Data inválida",
                JOptionPane.WARNING_MESSAGE
            );
        } catch (Exception e) {
            JOptionPane.showMessageDialog(
                this,
                "Erro ao cadastrar pagamento: " + e.getMessage(),
                "Erro",
                JOptionPane.ERROR_MESSAGE
            );
        }
        
    }//GEN-LAST:event_jBCadastrarActionPerformed

    private void jBAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBAtualizarActionPerformed
        // TODO add your handling code here:
        String idTexto = jTIDPagamento.getText().trim();
        String valorTexto = jTValor.getText().trim().replace(",", ".");
        String dataTexto = jTDataHora.getText().trim();
        String demandaTexto = jTIDDemanda.getText().trim();
        String formaTexto = jTIDFormaPagamento.getText().trim();

        if (idTexto.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Selecione um pagamento na tabela.",
                "Atenção",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (valorTexto.isEmpty() || dataTexto.isEmpty()
                || demandaTexto.isEmpty() || formaTexto.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Preencha todos os campos do pagamento.",
                "Campos obrigatórios",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        try {
            int id = Integer.parseInt(idTexto);
            BigDecimal valor = new BigDecimal(valorTexto);
            LocalDateTime dataHora = LocalDateTime.parse(dataTexto);
            int idDemanda = Integer.parseInt(demandaTexto);
            int idForma = Integer.parseInt(formaTexto);

            PagamentoControle controle = new PagamentoControle();

            boolean atualizado = controle.atualizar(
                id, valor, dataHora, idDemanda, idForma
            );

            if (atualizado) {
                carregarPagamentos();
                limparCampos();

                JOptionPane.showMessageDialog(
                    this,
                    "Pagamento atualizado com sucesso!",
                    "Atualização",
                    JOptionPane.INFORMATION_MESSAGE
                );
            } else {
                JOptionPane.showMessageDialog(
                    this,
                    "Pagamento não encontrado ou não atualizado.",
                    "Aviso",
                    JOptionPane.WARNING_MESSAGE
                );
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(
                this,
                "Verifique o ID, o valor e os IDs relacionados.",
                "Dados inválidos",
                JOptionPane.WARNING_MESSAGE
            );
        } catch (java.time.format.DateTimeParseException e) {
            JOptionPane.showMessageDialog(
                this,
                "Data inválida. Utilize o formato yyyy-MM-ddTHH:mm:ss.",
                "Data inválida",
                JOptionPane.WARNING_MESSAGE
            );
        } catch (Exception e) {
            JOptionPane.showMessageDialog(
                this,
                "Erro ao atualizar pagamento: " + e.getMessage(),
                "Erro",
                JOptionPane.ERROR_MESSAGE
            );
        }
        
    }//GEN-LAST:event_jBAtualizarActionPerformed

