private void carregarPagamentos() {
    try {
        PagamentoControle controle = new PagamentoControle();
        List<Pagamento> pagamentos = controle.listarTodos();

        DefaultTableModel modelo =
            (DefaultTableModel) jTResultado.getModel();

        modelo.setRowCount(0);

        for (Pagamento pagamento : pagamentos) {
            modelo.addRow(new Object[]{
                pagamento.getIdPagamento(),
                pagamento.getValorPagamento(),
                pagamento.getDataPagamento(),
                pagamento.getIdDemanda(),
                pagamento.getIdForma()
            });
        }

        modelo.fireTableDataChanged();

        System.out.println(
            "Pagamentos encontrados: " + pagamentos.size()
        );

    } catch (Exception e) {
        JOptionPane.showMessageDialog(
            this,
            "Erro ao carregar pagamentos: " + e.getMessage(),
            "Erro",
            JOptionPane.ERROR_MESSAGE
        );
        e.printStackTrace();
    }
}

