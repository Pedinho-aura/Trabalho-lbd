    private void jBExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBExcluirActionPerformed
        // TODO add your handling code here:
        String idTexto = jTIDPagamento.getText().trim();

        if (idTexto.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Selecione um pagamento na tabela.",
                "Atenção",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        int confirmacao = JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente excluir este pagamento?",
            "Confirmar exclusão",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
        );

        if (confirmacao != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            int id = Integer.parseInt(idTexto);

            PagamentoControle controle = new PagamentoControle();
            boolean excluido = controle.excluir(id);

            if (excluido) {
                carregarPagamentos();
                limparCampos();

                JOptionPane.showMessageDialog(
                    this,
                    "Pagamento excluído com sucesso!",
                    "Exclusão",
                    JOptionPane.INFORMATION_MESSAGE
                );
            } else {
                JOptionPane.showMessageDialog(
                    this,
                    "Pagamento não encontrado ou não excluído.",
                    "Aviso",
                    JOptionPane.WARNING_MESSAGE
                );
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(
                this,
                "O ID do pagamento é inválido.",
                "Dados inválidos",
                JOptionPane.WARNING_MESSAGE
            );
        } catch (Exception e) {
            JOptionPane.showMessageDialog(
                this,
                "Erro ao excluir pagamento: " + e.getMessage(),
                "Erro",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_jBExcluirActionPerformed

