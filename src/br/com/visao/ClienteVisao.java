    private void jBCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBCadastrarActionPerformed
        // TODO add your handling code here:
        String nome = jTNome.getText().trim();

        if (nome.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Informe o nome do cliente.",
                "Campo obrigatório",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        try {
            ClienteControle controle = new ClienteControle();

            int idGerado = controle.cadastrar(nome);

            carregarClientes();

            jTCliente.setText(String.valueOf(idGerado));
            jTNome.setText("");

            JOptionPane.showMessageDialog(
                this,
                "Cliente cadastrado com sucesso!",
                "Cadastro",
                JOptionPane.INFORMATION_MESSAGE
            );

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                this,
                "Erro ao cadastrar cliente: " + e.getMessage(),
                "Erro",
                JOptionPane.ERROR_MESSAGE
            );
}

    }//GEN-LAST:event_jBCadastrarActionPerformed

    private void jTResultadoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTResultadoMouseClicked
        // TODO add your handling code here:
        
        int linha = jTResultado.getSelectedRow();

        if (linha >= 0) {
            jTCliente.setText(
                jTResultado.getValueAt(linha, 0).toString()
            );

            jTNome.setText(
                jTResultado.getValueAt(linha, 1).toString()
            );
        }
        
        
        int linha1 = jTResultado.getSelectedRow();

        if (linha1 >= 0) {
            jTCliente.setText(
                jTResultado.getValueAt(linha1, 0).toString()
            );

            jTNome.setText(
                jTResultado.getValueAt(linha1, 1).toString()
            );
        }


    }//GEN-LAST:event_jTResultadoMouseClicked

    private void jBExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBExcluirActionPerformed
        // TODO add your handling code here:
        String idTexto = jTCliente.getText().trim();

        if (idTexto.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Selecione um cliente na tabela.",
                "Atenção",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        int confirmacao = JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente excluir este cliente?",
            "Confirmar exclusão",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
        );

        if (confirmacao != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            int id = Integer.parseInt(idTexto);

            ClienteControle controle = new ClienteControle();
            boolean excluido = controle.excluir(id);

            if (excluido) {
                carregarClientes();
                jTCliente.setText("");
                jTNome.setText("");

                JOptionPane.showMessageDialog(
                    this,
                    "Cliente excluído com sucesso!",
                    "Exclusão",
                    JOptionPane.INFORMATION_MESSAGE
                );
            } else {
                JOptionPane.showMessageDialog(
                    this,
                    "Não foi possível excluir o cliente.",
                    "Aviso",
                    JOptionPane.WARNING_MESSAGE
                );
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(
                this,
                "O ID do cliente é inválido.",
                "Erro",
                JOptionPane.ERROR_MESSAGE
            );
        } catch (Exception e) {
            JOptionPane.showMessageDialog(
                this,
                "Erro ao excluir cliente: " + e.getMessage(),
                "Erro",
                JOptionPane.ERROR_MESSAGE
            );
        }

    }//GEN-LAST:event_jBExcluirActionPerformed

